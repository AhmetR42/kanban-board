// t('columns.todo', 'nl') or t('progress', 'en', { done: 1, total: 4 })
export function t(key, locale = 'en', params = {}) {
    const lookup = (dict) => key.split('.').reduce((value, part) => value?.[part], dict);
    const text = lookup(messages[locale]) ?? lookup(messages.en) ?? key;
    return String(text).replace(/\{(\w+)\}/g, (match, name) => (name in params ? params[name] : match));
}
